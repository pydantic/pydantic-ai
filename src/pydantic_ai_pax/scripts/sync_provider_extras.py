"""Regenerate Pax's provider extras and `all` from `pydantic-ai-slim`'s extras, and the `pydantic-clai2` shim's extras.

Pax mirrors every `pydantic-ai-slim` extra not in `EXCLUDED`. Exits 1 when a file was out of date,
after rewriting it (or, with `--check`, without rewriting it), so pre-commit and CI catch drift:

```bash
python src/pydantic_ai_pax/scripts/sync_provider_extras.py
```
"""

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).parents[3]
SLIM = ROOT / 'pydantic_ai_slim' / 'pyproject.toml'
PAX = ROOT / 'src' / 'pydantic_ai_pax' / 'pyproject.toml'
SHIM = ROOT / 'src' / 'pydantic_clai2' / 'pyproject.toml'
COMMAND = 'python src/pydantic_ai_pax/scripts/sync_provider_extras.py'

EXCLUDED: dict[str, str] = {
    'logfire': 'Pax depends on `logfire[httpx]` directly.',
    'sentence-transformers': 'Embeddings only; Pax runs no embedder.',
    'voyageai': 'Embeddings only; Pax runs no embedder.',
    'duckduckgo': 'A tool, not a model provider; plugins install tools through `pydantic-ai-harness` extras.',
    'tavily': 'A tool, not a model provider; plugins install tools through `pydantic-ai-harness` extras.',
    'exa': 'A tool, not a model provider; plugins install tools through `pydantic-ai-harness` extras.',
    'web-fetch': 'A tool, not a model provider; plugins install tools through `pydantic-ai-harness` extras.',
    'cli': 'The `clai` CLI; Pax is its own CLI and depends on what it needs directly.',
    'realtime': 'Speech-to-speech sessions, which Pax does not run.',
    'openai-realtime': 'Speech-to-speech sessions, which Pax does not run.',
    'google-realtime': 'Speech-to-speech sessions, which Pax does not run.',
    'xai-realtime': 'Speech-to-speech sessions, which Pax does not run.',
    'elevenlabs-agents-realtime': 'Speech-to-speech sessions, which Pax does not run.',
    'elevenlabs-realtime': 'Speech-to-speech sessions, which Pax does not run.',
    'mcp': 'Installed by default.',
    'mcp-tasks': 'Explicit MCP task execution pulls the FastMCP server stack; Pax does not use it.',
    'evals': 'Pydantic Evals, which Pax does not use.',
    'ui': 'UI adapters mounted in your own app; Pax serves its own web UI.',
    'ag-ui': 'UI adapters mounted in your own app; Pax serves its own web UI.',
    'web': '`Agent.to_web()`; Pax serves its own web UI with dependencies it declares.',
    'retries': 'The legacy HTTPX retry helpers, which Pax does not use.',
    'temporal': 'Durable execution, which Pax does not use.',
    'dbos': 'Durable execution, which Pax does not use.',
    'prefect': 'Durable execution, which Pax does not use.',
    'spec': 'YAML agent specs, which Pax does not load.',
}
"""The `pydantic-ai-slim` extras Pax does not mirror, each with the reason."""

LOCAL = 'local'
"""The `/sandbox` extra `all` leaves out: its SDKs have no Windows wheel."""

BEGIN = f'# BEGIN generated by {COMMAND}; edit `EXCLUDED` there, not this block.\n'
END = '# END generated\n'
SECTION = '[tool.hatch.metadata.hooks.uv-dynamic-versioning.optional-dependencies]\n'


def extras(text: str) -> dict[str, list[str]]:
    """A project's extras, which these projects declare through the `uv-dynamic-versioning` metadata hook."""
    return tomllib.loads(text)['tool']['hatch']['metadata']['hooks']['uv-dynamic-versioning']['optional-dependencies']


def pin(text: str, package: str) -> str:
    """The version pin of the project's dependency on `package`, such as `==0.{{ minor }}...`."""
    dependencies: list[str] = tomllib.loads(text)['tool']['hatch']['metadata']['hooks']['uv-dynamic-versioning'][
        'dependencies'
    ]
    [rest] = [d.removeprefix(package) for d in dependencies if d.startswith((f'{package}[', f'{package}=='))]
    return rest.partition(']')[2] if rest.startswith('[') else rest


def render_pax(*, slim: str, pax: str) -> str:
    """Pax's project with its generated block rewritten from `slim`'s extras."""
    slim_extras = extras(slim)
    if gone := sorted(set(EXCLUDED) - set(slim_extras)):
        raise ValueError(f'`pydantic-ai-slim` no longer has {gone}: remove them from `EXCLUDED` in {COMMAND}.')
    mirrored = [name for name in slim_extras if name not in EXCLUDED]
    slim_pin, harness_pin = pin(pax, 'pydantic-ai-slim'), pin(pax, 'pydantic-ai-harness')
    sandboxes = sorted(
        name for name, deps in extras(pax).items() if name != LOCAL and deps[0].startswith('pydantic-ai-harness[')
    )
    block = ''.join(f'{name} = ["pydantic-ai-slim[{name}]{slim_pin}"]\n' for name in mirrored)
    block += (
        '# Every provider above and every `/sandbox` extra below but `local`, whose SDKs have no Windows wheel.\n'
        'all = [\n'
        f'    "pydantic-ai-slim[{",".join(sorted(mirrored))}]{slim_pin}",\n'
        f'    "pydantic-ai-harness[{",".join(sandboxes)}]{harness_pin}",\n'
        ']\n'
    )
    before, _, rest = pax.partition(BEGIN)
    _, _, after = rest.partition(END)
    return f'{before}{BEGIN}{block}{END}{after}'


def render_shim(*, pax: str, shim: str) -> str:
    """The `pydantic-clai2` shim's project offering every Pax extra, so its installs keep working."""
    shim_pin = pin(shim, 'pydantic-ai-pax')
    before, _, rest = shim.partition(SECTION)
    _, _, after = rest.partition('\n[')
    block = ''.join(f'{name} = ["pydantic-ai-pax[{name}]{shim_pin}"]\n' for name in extras(pax))
    return f'{before}{SECTION}{block}\n[{after}'


def main(argv: list[str]) -> int:
    """Rewrite Pax's and the shim's projects unless `--check`; return 1 if either was out of date."""
    pax = PAX.read_text(encoding='utf-8')
    shim = SHIM.read_text(encoding='utf-8')
    new_pax = render_pax(slim=SLIM.read_text(encoding='utf-8'), pax=pax)
    stale = [
        (path, new)
        for path, old, new in ((PAX, pax, new_pax), (SHIM, shim, render_shim(pax=new_pax, shim=shim)))
        if old != new
    ]
    for path, new in stale:
        if '--check' in argv:
            print(f'{path.relative_to(ROOT)} is out of date; run `{COMMAND}`.')
        else:
            path.write_text(new, encoding='utf-8')
            print(f'Regenerated the extras in {path.relative_to(ROOT)}.')
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
