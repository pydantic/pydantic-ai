#!/usr/bin/env python
"""Regenerate `pydantic_ai/providers/_openrouter_input_modalities.py` from OpenRouter's model list.

`OpenRouterProvider.model_profile` sets a model's image, audio and video input flags from the snapshot this writes, so
that a file a model can't take is replaced by a note instead of failing the request. The snapshot is checked in so
that profiles stay the same from run to run and resolving one needs no network access.

The model list (https://openrouter.ai/api/v1/models) needs no API key. Each model's `architecture.input_modalities`
is reduced to the kinds among `KINDS`: `text` every model takes, and `file` is left out because OpenRouter parses a
PDF to text for a model that doesn't take files. A model that takes text only is kept with no kinds, as that is what
turns its flags off. A `:tag` variant such as `:free` is kept only when it takes other kinds than its base model,
which the provider falls back to. Models are sorted by ID, so a refresh changes only the lines whose models changed.

`.github/workflows/openrouter-input-modalities.yml` runs this weekly and opens a pull request when the snapshot
changes. To run it by hand: `uv run python scripts/update_openrouter_input_modalities.py`.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import httpx
from pydantic import BaseModel

MODEL_LIST_URL = 'https://openrouter.ai/api/v1/models'
OUTPUT = Path(__file__).parents[1] / 'pydantic_ai_slim/pydantic_ai/providers/_openrouter_input_modalities.py'
KINDS = ('image', 'audio', 'video')

# The snapshot is Python source, so a model ID from the network goes into it only when it can't break out of a string.
_MODEL_ID = re.compile(r'~?[A-Za-z0-9][\w.-]*/[\w.-]+(?::[\w.-]+)?', re.ASCII)

_HEADER = '''\
"""The kinds of file each model on OpenRouter takes, by model ID, from `architecture.input_modalities` in its model list.

Generated by `scripts/update_openrouter_input_modalities.py` from https://openrouter.ai/api/v1/models. Don't edit it by
hand: `.github/workflows/openrouter-input-modalities.yml` refreshes it weekly. See the script for what is left out.
"""

from __future__ import annotations as _annotations

from collections.abc import Mapping
from typing import Literal

InputModality = Literal['image', 'audio', 'video']

OPENROUTER_INPUT_MODALITIES: Mapping[str, tuple[InputModality, ...]] = {
'''


class Architecture(BaseModel):
    """The part of a listed model that says what it takes."""

    input_modalities: list[str] | None = None


class ListedModel(BaseModel):
    """One model in the list, with only the fields the snapshot uses."""

    id: str
    architecture: Architecture | None = None


class ModelList(BaseModel):
    """The response of the model list endpoint."""

    data: list[ListedModel]


def input_modalities(model_list: ModelList) -> dict[str, tuple[str, ...]]:
    """The kinds among `KINDS` each model takes, by model ID, for the models whose list entry has them."""
    listed: dict[str, tuple[str, ...]] = {}
    for model in model_list.data:
        if model.architecture is None or model.architecture.input_modalities is None:
            continue
        if not _MODEL_ID.fullmatch(model.id):
            raise ValueError(f'Unexpected model ID in the OpenRouter model list: {model.id!r}')
        listed[model.id] = tuple(kind for kind in KINDS if kind in model.architecture.input_modalities)
    return {
        model_id: kinds
        for model_id, kinds in sorted(listed.items())
        if ':' not in model_id or listed.get(model_id.split(':', 1)[0]) != kinds
    }


def render(modalities: dict[str, tuple[str, ...]]) -> str:
    """The snapshot module's source, formatted as `ruff format` leaves it."""
    lines = [_HEADER]
    for model_id, kinds in sorted(modalities.items()):
        value = '(' + ', '.join(repr(kind) for kind in kinds) + (',)' if len(kinds) == 1 else ')')
        lines.append(f'    {model_id!r}: {value},\n')
    lines.append('}\n')
    return ''.join(lines)


def main() -> int:
    """Fetch the model list and write the snapshot."""
    response = httpx.get(MODEL_LIST_URL, timeout=60, follow_redirects=True)
    response.raise_for_status()
    modalities = input_modalities(ModelList.model_validate_json(response.content))
    if not modalities:
        print('The OpenRouter model list has no models with input modalities', file=sys.stderr)
        return 1
    OUTPUT.write_text(render(modalities), encoding='utf-8')
    print(f'Wrote {len(modalities)} models to {OUTPUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
